<?php

namespace StrictlyLaravel\Routes;

use Illuminate\Filesystem\Filesystem;

/**
 * Writes `route-keys.ts` into the generated directory: the field each model's routes bind it by when they name none
 * (its route key name), as an augmentation of the npm package's `RouteKeyFields`. That is what makes
 * `RouteKey<'Issue', number>` the key of that field, `Key<'Issue', 'number', number>`, as the model's route parameters
 * take it (Problems P-003, P-128):
 *
 *     declare module '@mrsafalpiya/strictly-laravel/routes' {
 *         interface RouteKeyFields {
 *             "Issue": "number";
 *         }
 *     }
 *
 * Nothing imports it: tsconfig includes every file under resources/js, so the augmentation applies to the whole app.
 */
final class RouteKeyFieldsModule
{
    public const string FILE = 'route-keys.ts';

    /**
     * @param  array<string, string>  $fields  The route key name of each model, by its brand (RouteKeys::routeKeyFields()).
     */
    public static function write(array $fields, string $outputDirectory, Filesystem $files): void
    {
        $lines = array_map(
            fn (string $brand, string $field): string => sprintf('        %s: %s;', self::literal($brand), self::literal($field)),
            array_keys($fields),
            $fields,
        );

        $files->put("{$outputDirectory}/".self::FILE, implode("\n", [
            '// Generated by `php artisan strictly:generate` from the app\'s routes and routes/channels.php. Do not edit.',
            'export {};',
            '',
            '/** The field each model\'s routes bind it by when they name none: what `RouteKey<\'Issue\', number>` is the key of. */',
            sprintf("declare module '%s' {", WayfinderTemplates::TYPES_MODULE),
            '    interface RouteKeyFields {',
            ...$lines,
            '    }',
            '}',
            '',
        ]));
    }

    /** A TypeScript string literal. */
    private static function literal(string $value): string
    {
        return json_encode($value, JSON_THROW_ON_ERROR | JSON_UNESCAPED_SLASHES | JSON_UNESCAPED_UNICODE);
    }
}
